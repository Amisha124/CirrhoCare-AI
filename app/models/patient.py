from datetime import datetime

from app.models import db


class Patient(db.Model):
    __tablename__ = "patients"

    id = db.Column(db.Integer, primary_key=True)
    full_name = db.Column(db.String(140), nullable=False, index=True)
    portal_id = db.Column(db.String(40), unique=True, nullable=True, index=True)
    age = db.Column(db.Integer, nullable=False)
    gender = db.Column(db.String(20), nullable=False)
    phone = db.Column(db.String(30))
    email = db.Column(db.String(160))
    bilirubin = db.Column(db.Float, default=None)
    direct_bilirubin = db.Column(db.Float, default=None)
    albumin = db.Column(db.Float, default=None)
    sgot = db.Column(db.Float, default=None)
    sgpt = db.Column(db.Float, default=None)
    platelets = db.Column(db.Float, default=None)
    cholesterol = db.Column(db.Float, default=None)
    prothrombin = db.Column(db.Float, default=None)
    ascites = db.Column(db.Boolean, default=False)
    hepatomegaly = db.Column(db.Boolean, default=False)
    spiders = db.Column(db.Boolean, default=False)
    edema = db.Column(db.Boolean, default=False)
    copper = db.Column(db.Float, default=None)
    alk_phos = db.Column(db.Float, default=None)
    triglycerides = db.Column(db.Float, default=None)
    latest_risk_label = db.Column(db.String(30), default="Pending")
    latest_risk_percent = db.Column(db.Float, default=0)
    treatment_status = db.Column(db.String(80), default="Awaiting Doctor Review")
    treatment_status_updated_at = db.Column(db.DateTime, nullable=True)
    lab_workflow_status = db.Column(db.String(60), default="Registered")
    treatment_completed_at = db.Column(db.DateTime, nullable=True)
    treatment_completed_by_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=True)
    treatment_completed_notes = db.Column(db.Text, nullable=True)
    diet_plan = db.Column(db.Text, nullable=True)
    care_instructions = db.Column(db.Text, nullable=True)
    follow_up_date = db.Column(db.Date, nullable=True)
    created_by_id = db.Column(db.Integer, db.ForeignKey("users.id"))
    assigned_doctor_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=True)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    created_by = db.relationship("User", back_populates="patients", foreign_keys=[created_by_id])
    assigned_doctor = db.relationship("User", foreign_keys=[assigned_doctor_id])
    treatment_completed_by = db.relationship("User", foreign_keys=[treatment_completed_by_id])
    predictions = db.relationship("Prediction", back_populates="patient", cascade="all, delete-orphan")
    prescriptions = db.relationship("Prescription", back_populates="patient", cascade="all, delete-orphan")
    reports = db.relationship("Report", back_populates="patient", cascade="all, delete-orphan")
    appointments = db.relationship("Appointment", back_populates="patient", cascade="all, delete-orphan")
    lab_orders = db.relationship("LabOrder", back_populates="patient", cascade="all, delete-orphan")
